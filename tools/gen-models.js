function main() {
  fs.mkdirSync(MODEL_ITEM, { recursive: true });
  fs.mkdirSync(MODEL_ENTITY, { recursive: true });

  for (const name of ITEMS) {
    const model = {
      parent: 'minecraft:item/generated',
      textures: { layer0: 'anglertackle:item/' + name },
    };
    fs.writeFileSync(path.join(MODEL_ITEM, name + '.json'), JSON.stringify(model, null, 2));
  }
  console.log('物品模型: ' + ITEMS.length + ' 个');

  fs.writeFileSync(path.join(MODEL_ENTITY, 'bobber.json'), JSON.stringify(BOBBER_MODEL, null, 2));
  console.log('实体模型: bobber.json');
}

main();
